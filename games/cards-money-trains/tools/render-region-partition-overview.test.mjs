/**
 * Точечная проверка геометрических помощников обзорного рендерера разбиения
 * карты на области.
 *
 * Зачем нужен этот файл: `pointInRing()` и `distancePointToRing()` — классический
 * тест «точка внутри многоугольника» (ray casting, «трассировка луча»: точка
 * считается внутри, если воображаемый луч от неё вбок пересекает границу
 * фигуры нечётное число раз) и измерение расстояния до границы кольца.
 * Обе функции много лет молча работали неправильно из-за опечатки в цикле:
 * `j = i += 1` — префиксный инкремент — присваивал `j` уже увеличенное
 * значение `i`, из-за чего два соседних индекса ребра совпадали, ребро
 * вырождалось в точку, и ни одно пересечение (кроме самого первого,
 * замыкающего ребра) никогда не засчитывалось. Итог был предсказуемо неверным:
 * `pointInRing()` объявляла почти любую точку внутри фигуры лежащей снаружи.
 * Правильная форма — постфиксный инкремент `j = i++`, отдающий предыдущее
 * значение `i` перед увеличением.
 *
 * Этот файл не пересобирает настоящий черновик разбиения (это дорого и не
 * нужно для проверки чистой геометрической функции) — как и соседний
 * `render-region-partition-doubt-crops.test.mjs`, он строит маленькие
 * придуманные кольца, для которых правильный ответ известен заранее.
 */

import assert from "node:assert/strict";
import test from "node:test";

import { distancePointToRing, pointInRing } from "./render-region-partition-overview.mjs";

// ---------------------------------------------------------------------------
// pointInRing(): три случая, которых просит задание — обычный квадрат,
// точка снаружи и «кольцевая» область с дыркой (одно кольцо-«замочная
// скважина», где щель соединяет внешнюю и внутреннюю границу).
// ---------------------------------------------------------------------------

test("pointInRing: центр простого квадрата — внутри", () => {
  const square = [[0, 0], [10, 0], [10, 10], [0, 10]];
  assert.equal(
    pointInRing(5, 5, square),
    true,
    "центр квадрата 0..10 обязан быть внутри — это и есть регрессия: при " +
      "сломанном `j = i += 1` эта же проверка возвращала false"
  );
});

test("pointInRing: точка снаружи фигуры — снаружи", () => {
  const square = [[0, 0], [10, 0], [10, 10], [0, 10]];
  assert.equal(pointInRing(50, 50, square), false);
});

test("pointInRing: точка внутри дырки кольцевой области — снаружи", () => {
  // Одно замкнутое кольцо в форме «замочной скважины» (keyhole): внешний
  // квадрат 0..20, внутренний квадрат-дырка 5..15, и узкая щель по x=0..5 на
  // высоте y=10, соединяющая внешнюю границу с внутренней. Так одно кольцо
  // (без отдельного списка "внутренних колец") кодирует область с дыркой —
  // ровно то, что exteriorRing получает от полигонизатора для области с
  // отверстием, вырезанным щелью в geometryFingerprint-совместимом виде.
  const ringWithHole = [
    [0, 0], [20, 0], [20, 20], [0, 20], [0, 10],
    [5, 10], [5, 5], [15, 5], [15, 15], [5, 15], [5, 10],
    [0, 10], [0, 0]
  ];

  // Центр дырки — должен быть снаружи фигуры (дырка — не материал области).
  assert.equal(
    pointInRing(10, 10, ringWithHole),
    false,
    "центр дырки кольцевой фигуры обязан быть снаружи"
  );

  // Контрольная точка в самом материале фигуры (между внешней и внутренней
  // границей) — обязана остаться внутри, иначе проверка была бы полезна
  // только для дырки, но не доказывала бы, что окружающий материал остался
  // читаемым как «внутри».
  assert.equal(
    pointInRing(2, 2, ringWithHole),
    true,
    "точка в материале кольцевой фигуры (не в дырке) обязана быть внутри"
  );
});

// ---------------------------------------------------------------------------
// distancePointToRing(): та же самая опечатка ломала и эту функцию (для всех
// рёбер, кроме замыкающего, она мерила расстояние до вырожденного "отрезка"
// нулевой длины — то есть до одной вершины, а не до настоящего ребра).
// ---------------------------------------------------------------------------

test("distancePointToRing: расстояние до середины стороны равно половине стороны", () => {
  const square = [[0, 0], [10, 0], [10, 10], [0, 10]];
  // Точка (5, -5) стоит строго под серединой нижней стороны на расстоянии 5.
  // При сломанном цикле функция меряла бы расстояние до одной из вершин
  // (0,0) или (10,0) — по теореме Пифагора это было бы больше 5.
  assert.equal(distancePointToRing(5, -5, square), 5);
});

test("distancePointToRing: точка на границе — расстояние 0", () => {
  const square = [[0, 0], [10, 0], [10, 10], [0, 10]];
  assert.equal(distancePointToRing(0, 5, square), 0);
});
